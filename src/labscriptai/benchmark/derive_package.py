"""Derive benchmark package sidecars from a generated Opentrons protocol."""

from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from labscriptai.benchmark.tasks import AuthoringTask
from labscriptai.benchmark.validators.opentrons import extract_protocol_refs


def derive_package_from_protocol(
    package_dir: Path,
    task: AuthoringTask,
    *,
    model_id: str,
    scaffold_id: str = "protocol-py-derived-v0.4",
    overwrite: bool = True,
) -> dict[str, Any]:
    """Create manifest/setup sidecars from protocol.py for fair py-only scoring."""

    protocol_path = package_dir / "protocol.py"
    if not protocol_path.exists():
        raise FileNotFoundError(f"protocol.py not found: {protocol_path}")
    protocol_text = protocol_path.read_text(encoding="utf-8")
    protocol_hash = "sha256:" + hashlib.sha256(protocol_text.encode("utf-8")).hexdigest()
    setup_path = package_dir / "setup_card.html"
    manifest_path = package_dir / "manifest.json"

    labware, instruments = extract_protocol_refs(protocol_path)
    manifest = _derive_manifest(
        task,
        model_id=model_id,
        scaffold_id=scaffold_id,
        protocol_hash=protocol_hash,
        labware=labware,
        instruments=instruments,
        protocol_text=protocol_text,
    )
    setup_html = _derive_setup_card(task, labware=labware, instruments=instruments)

    written: list[str] = []
    if overwrite or not manifest_path.exists():
        manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        written.append("manifest.json")
    if overwrite or not setup_path.exists():
        setup_path.write_text(setup_html, encoding="utf-8")
        written.append("setup_card.html")
    return {
        "derived": True,
        "written": written,
        "protocol_hash": protocol_hash,
        "labware_count": len(labware),
        "instrument_count": len(instruments),
        "scaffold_id": scaffold_id,
    }


def _derive_manifest(
    task: AuthoringTask,
    *,
    model_id: str,
    scaffold_id: str,
    protocol_hash: str,
    labware: set[tuple[str, str]],
    instruments: set[tuple[str, str]],
    protocol_text: str,
) -> dict[str, Any]:
    expected_handoffs = list(task.off_platform_handoff)
    return {
        "schema_version": "0.4",
        "task_id": task.task_id,
        "system_id": "labscriptai",
        "model_id": model_id,
        "scaffold_id": scaffold_id,
        "prompt_hash": "sha256:" + hashlib.sha256(task.prompt.encode("utf-8")).hexdigest(),
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "hashes": {"protocol_py": protocol_hash},
        "deck": {
            "labware": [
                {"load_name": load_name, "slot": str(slot)}
                for load_name, slot in sorted(labware, key=lambda item: (str(item[1]), item[0]))
            ],
            "modules": [],
            "instruments": [
                {"instrument_name": name, "name": name, "mount": mount}
                for name, mount in sorted(instruments, key=lambda item: (item[1], item[0]))
            ],
        },
        "reagents": _derive_reagents(task),
        "tips": {
            "tips_required": max(1, _estimate_tip_use(protocol_text)),
            "tips_available": max(96, _estimate_tiprack_capacity(labware)),
        },
        "risk_flags": list(task.spec.expected_risk_flags),
        "critical_failures": [],
        "off_platform_handoff": {
            "declared": bool(expected_handoffs),
            "instrument": expected_handoffs[0] if expected_handoffs else None,
        },
        "tool_permissions": ["validate_package", "simulate_protocol"],
        "budget": {"attempts": 8, "wall_min": 30, "tokens": 24000},
        "derive": {
            "source": "protocol.py",
            "method": "static_protocol_refs",
            "note": "Benchmark sidecars were generated by the harness, not by the model.",
        },
    }


def _derive_reagents(task: AuthoringTask) -> list[dict[str, Any]]:
    reagents: list[dict[str, Any]] = []
    samples = task.spec.default_samples or 1
    for reagent in task.spec.reagents:
        item: dict[str, Any] = {"name": reagent.name}
        if reagent.volume_per_sample_uL is not None:
            item["volume_per_sample_uL"] = reagent.volume_per_sample_uL
            item["required_volume_ul"] = reagent.volume_per_sample_uL * samples
        if reagent.source:
            item["source"] = reagent.source
        reagents.append(item)
    return reagents


def _estimate_tip_use(protocol_text: str) -> int:
    text = _without_helper_defs(protocol_text)
    return len(re.findall(r"\.\s*pick_up_tip\s*\(", text)) + len(
        re.findall(r"(?<!def )_safe_pick_up_tip\s*\(", text)
    )


def _without_helper_defs(protocol_text: str) -> str:
    lines = protocol_text.splitlines()
    kept: list[str] = []
    skipping = False
    for line in lines:
        if line.startswith("def _safe_pick_up_tip("):
            skipping = True
            continue
        if skipping and line and not line.startswith((" ", "\t")):
            skipping = False
        if not skipping:
            kept.append(line)
    return "\n".join(kept)


def _estimate_tiprack_capacity(labware: set[tuple[str, str]]) -> int:
    tiprack_count = sum(1 for load_name, _slot in labware if "tiprack" in load_name.lower())
    return max(1, tiprack_count) * 96


def _derive_setup_card(
    task: AuthoringTask,
    *,
    labware: set[tuple[str, str]],
    instruments: set[tuple[str, str]],
) -> str:
    labware_rows = "\n".join(
        f"<tr><td>{slot}</td><td>{load_name}</td></tr>"
        for load_name, slot in sorted(labware, key=lambda item: (str(item[1]), item[0]))
    )
    instrument_rows = "\n".join(
        f"<tr><td>{mount}</td><td>{name}</td></tr>"
        for name, mount in sorted(instruments, key=lambda item: (item[1], item[0]))
    )
    risks = ", ".join(task.spec.expected_risk_flags) or "None declared in task manifest"
    return (
        "<!doctype html>\n"
        "<html><body>\n"
        f"<h1>Setup Card: {task.task_id}</h1>\n"
        "<p>This card was derived by the benchmark harness from protocol.py.</p>\n"
        "<h2>Deck</h2>\n"
        "<table><thead><tr><th>Slot</th><th>Labware</th></tr></thead><tbody>\n"
        f"{labware_rows}\n"
        "</tbody></table>\n"
        "<h2>Instruments</h2>\n"
        "<table><thead><tr><th>Mount</th><th>Instrument</th></tr></thead><tbody>\n"
        f"{instrument_rows}\n"
        "</tbody></table>\n"
        f"<h2>Task Risks</h2><p>{risks}</p>\n"
        "</body></html>\n"
    )
